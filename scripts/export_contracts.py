"""Small fail-closed generator for Phase 01 Pydantic schemas and TS types only."""

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from t1d_api.contracts import ErrorResponse, LivenessResponse, ReadinessResponse, SessionResponse
from t1d_api.data.schemas import CGMReceipt, EventReceipt, MealReceipt
from t1d_vision.contracts import VisionAvailability, VisionResult

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "packages/shared-contracts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        required = set(schema.get("required", []))
        fields = []
        for name, value in schema.get("properties", {}).items():
            # Responses include defaults at serialization; emit all properties required.
            optional = "" if name in required or "default" in value else "?"
            fields.append(f"  readonly {name}{optional}: {ts_type(value)};")
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported schema node: {schema}")


def artifacts() -> dict[Path, str]:
    definitions: dict[str, Any] = {}
    models: list[type[BaseModel]] = [
        LivenessResponse,
        ReadinessResponse,
        ErrorResponse,
        SessionResponse,
        CGMReceipt,
        MealReceipt,
        EventReceipt,
        VisionAvailability,
        VisionResult,
    ]
    for model in models:
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    schema_text = (
        json.dumps(
            {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions},
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    ts = "// Generated by scripts/export_contracts.py. Do not edit.\n\n"
    ts += (
        "\n\n".join(
            f"export type {name} = {ts_type(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )
    return {OUT / "schema.json": schema_text, OUT / "index.ts": ts}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in artifacts().items():
        if options.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Contract drift: regenerate {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print("Shared contracts match backend schemas" if options.check else "Contracts generated")


if __name__ == "__main__":
    main()
